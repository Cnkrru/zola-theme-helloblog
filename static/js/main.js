// 搜索模块单独打包，首次聚焦或点击搜索框时才加载，避免首屏带上 minisearch
const lazySearch = () => {
  const input = document.querySelector('.search input')
  const url = document.querySelector('meta[name="search-script"]')?.content
  if (!input || !url) return

  let loading = false
  const load = () => {
    if (loading) return
    loading = true
    import(url)
      .then((mod) => mod.initSearch())
      .catch(() => {
        loading = false
      })
  }

  ;['focus', 'pointerdown', 'keydown'].forEach((ev) =>
    input.addEventListener(ev, load, { once: true }),
  )
}

document.addEventListener('DOMContentLoaded', () => {
  initHeader()
  twWorker()
  archiveView()
  initMusic()
  lazySearch()
  initLinkPage()
  initHitmap()
  initTagPage()
  initContent()
  initComments()
  initToc()
  initShare()
  initBackToTop()
  initParticle()
  initSidebar()
  webageStart()
})
